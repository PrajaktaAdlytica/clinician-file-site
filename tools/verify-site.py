from pathlib import Path
from html.parser import HTMLParser
from urllib.parse import urlsplit,unquote
import json,re
ROOT=Path(__file__).resolve().parents[1]
class Page(HTMLParser):
 def __init__(self,text):super().__init__();self.ids=[];self.links=[];self.tags=[];self.feed(text)
 def handle_starttag(self,tag,attrs):
  a=dict(attrs);self.tags.append((tag,a))
  if a.get('id'):self.ids.append(a['id'])
  for attr in ('src','href'):
   if a.get(attr):self.links.append((tag,a[attr]))
issues=[];pages={str(p.relative_to(ROOT)):Page(p.read_text()) for p in ROOT.glob('*.html')};checks=0
for name,page in pages.items():
 if len(page.ids)!=len(set(page.ids)):issues.append(f'{name}: duplicate IDs')
 for tag,href in page.links:
  u=urlsplit(href)
  if u.scheme or u.netloc:continue
  target=unquote(u.path) or name;file=ROOT/target
  if not file.exists():issues.append(f'{name}: missing {href}')
  elif u.fragment and target in pages and target!='demo.html' and u.fragment not in pages[target].ids:
   # Module rows on homepage are generated by its controller.
   if not re.fullmatch('module-[1-5]',u.fragment):issues.append(f'{name}: missing fragment {href}')
  checks+=1
 if not any(t=='meta' and a.get('name')=='viewport' for t,a in page.tags):issues.append(f'{name}: no viewport')
 if not any(t=='link' and a.get('rel')=='icon' for t,a in page.tags):issues.append(f'{name}: no favicon')
# Validate all icon names used by literal data-icon attributes and template icon() calls.
sprite=(ROOT/'assets/icons/sprite.svg').read_text();names=set(re.findall(r'id="([^"]+)"',sprite))
for file in list(ROOT.glob('*.html'))+list(ROOT.glob('*.js')):
 text=file.read_text()
 for name in set(re.findall(r'data-icon="([\w-]+)"',text)+re.findall(r"icon\('([\w-]+)'\)",text)):
  if name not in names:issues.append(f'{file.name}: missing icon {name}')
result={'htmlPages':len(pages),'localReferencesChecked':checks,'issues':issues}
(ROOT/'qa/site-checks.json').write_text(json.dumps(result,indent=2));print(json.dumps(result,indent=2));raise SystemExit(bool(issues))
